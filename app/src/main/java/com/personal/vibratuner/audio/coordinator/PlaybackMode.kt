package com.personal.vibratuner.audio.coordinator

/**
 * Режим порядка воспроизведения музыки (этап 3): одна кнопка мини-плеера
 * циклически переключает `OFF -> SHUFFLE -> REPEAT_ONE -> OFF`.
 *
 * Состояние живёт ТОЛЬКО в координаторе, в памяти: после перезапуска
 * приложения/сервиса режим снова `OFF`. Флаг глобального shuffle из DataStore
 * от него не зависит и не переключается — это разные вещи.
 */
enum class PlaybackMode {
    /** Существующее поведение: следующий трек по порядку, окончание -> следующий. */
    OFF,

    /** Следующий трек — случайный из текущей очереди/библиотеки, без повтора текущего. */
    SHUFFLE,

    /** Окончание трека перезапускает его же; ручной «дальше» по-прежнему переключает. */
    REPEAT_ONE;

    /** Следующее состояние по кругу для одной кнопки режима. */
    fun next(): PlaybackMode = when (this) {
        OFF -> SHUFFLE
        SHUFFLE -> REPEAT_ONE
        REPEAT_ONE -> OFF
    }
}
